"""Reproducible evaluation of the stale-standing rule.

Usage (from the project root):
    python scripts/evaluate_stale_standing.py
    python scripts/evaluate_stale_standing.py --data data/processed/food_insecurity_percentages.csv

Writes CSV tables and a Markdown report to evaluation/results/. Every number in
the report is computed here from the data file; nothing is typed in by hand.
"""

import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from foodshield import data as fsdata  # noqa: E402
from foodshield import evaluation as ev  # noqa: E402


def pct(x):
    return "n/a" if pd.isna(x) else f"{100 * x:.1f}%"


def num(x, digits=2):
    return "n/a" if pd.isna(x) else f"{x:.{digits}f}"


def build_report(data_path, sha, observations, results, n_boot, seed):
    by_h = results["by_horizon"]
    by_o = results["by_origin"]
    boot = results["primary_bootstrap"]
    attr = results["attrition"]
    lines = []
    add = lines.append

    add("# Evaluation: does higher-quarter standing persist? (stale-standing rule)")
    add("")
    add("Generated by `scripts/evaluate_stale_standing.py`. All values are computed from the data file below.")
    add("")
    add(f"- Data file: `{data_path.name}` (SHA-256 `{sha}`)")
    add(
        f"- Observations: {len(observations):,} rows, {observations['country_code'].nunique()} countries/areas, "
        f"reference years {int(observations['year'].min())}-{int(observations['year'].max())}"
    )
    add(f"- Bootstrap: {n_boot} country-clustered resamples, seed {seed}; pandas {pd.__version__}, numpy {np.__version__}")
    add("")
    add("## What is tested (and what is not)")
    add("")
    add(
        "The screening table now flags a country whose latest estimate is old as *higher last-known burden* when "
        "that estimate was in the higher quarter (75th percentile) of countries observed in its own reference year. "
        "That is only reasonable if relative standing persists. This evaluation measures, for countries observed "
        "again later, how often higher-quarter standing at year T is followed by higher-quarter standing at T + h. "
        "The primary horizon is h = 3 (non-overlapping three-year windows)."
    )
    add("")
    add(
        "It does **not** validate 'priority' (no ground truth exists), does not forecast, and cannot observe the "
        "future of countries that dropped out of the data."
    )
    add("")

    primary = by_h[(by_h["horizon"] == ev.PRIMARY_HORIZON)]
    add("## Primary result: horizon 3, pooled over all origins")
    add("")
    add("| Rule | Pairs | Flagged | High at T+3 (base rate) | Precision | Recall | Lift over base rate |")
    add("|---|---|---|---|---|---|---|")
    for _, r in primary.iterrows():
        add(
            f"| {r['rule']} | {int(r['pairs'])} | {int(r['flagged'])} | {int(r['high_at_target'])} ({pct(r['base_rate'])}) | "
            f"{pct(r['precision'])} ({pct(r['precision_ci_low'])}-{pct(r['precision_ci_high'])}) | "
            f"{pct(r['recall'])} ({pct(r['recall_ci_low'])}-{pct(r['recall_ci_high'])}) | {num(r['lift_over_base_rate'])} |"
        )
    add("")
    add("Intervals in brackets are Wilson 95% intervals that treat pairs as independent; they are optimistic because the same countries recur across origins.")
    if not boot.empty:
        b = boot.iloc[0]
        add("")
        add(
            f"Country-clustered bootstrap 95% intervals for the new rule at h = 3 ({int(b['n_countries'])} countries): "
            f"precision {pct(b['precision_boot_low'])}-{pct(b['precision_boot_high'])}, "
            f"recall {pct(b['recall_boot_low'])}-{pct(b['recall_boot_high'])}, "
            f"lift {num(b['lift_boot_low'])}-{num(b['lift_boot_high'])}."
        )
    add("")
    add("Baselines: the previous app gave stale countries no burden information (equivalent to flagging none of them, recall 0%). "
        "An uninformed flag would reach only the base rate. The 'cross-year cutoff' row compares the old estimate with the target year's cutoff.")
    add("")

    add("## By origin year (h = 3, new rule)")
    add("")
    add("| Origin | Target | Pairs | Flagged | Precision | Recall |")
    add("|---|---|---|---|---|---|")
    for _, r in by_o[by_o["horizon"] == ev.PRIMARY_HORIZON].iterrows():
        add(
            f"| {int(r['origin'])} | {int(r['target'])} | {int(r['pairs'])} | {int(r['flagged'])} | "
            f"{pct(r['precision'])} ({pct(r['precision_ci_low'])}-{pct(r['precision_ci_high'])}) | {pct(r['recall'])} |"
        )
    add("")

    add("## Secondary horizons (descriptive)")
    add("")
    add("| Horizon | Rule | Pairs | Precision | Recall | Base rate | Lift | Spearman (levels) |")
    add("|---|---|---|---|---|---|---|---|")
    for _, r in by_h.iterrows():
        add(
            f"| {int(r['horizon'])} | {r['rule']} | {int(r['pairs'])} | {pct(r['precision'])} | {pct(r['recall'])} | "
            f"{pct(r['base_rate'])} | {num(r['lift_over_base_rate'])} | {num(r['spearman_levels'], 3)} |"
        )
    add("")

    add("## Diagnostic: countries not observed again (h = 3)")
    add("")
    add("Truly stale countries cannot be scored on their missing future. This table shows whether countries that were *not* observed three years later looked different at the origin year.")
    add("")
    add("| Origin | Observed | Observed again | Not observed again | High share (observed again) | High share (not observed again) | High and not observed again |")
    add("|---|---|---|---|---|---|---|")
    for _, r in attr.iterrows():
        add(
            f"| {int(r['origin'])} | {int(r['observed_at_origin'])} | {int(r['retained'])} | {int(r['lost'])} | "
            f"{pct(r['share_high_retained'])} | {pct(r['share_high_lost'])} | {int(r['high_lost_count'])} |"
        )
    add("")
    add("## Limits")
    add("")
    add("- Persistence of relative standing between observed years is not a forecast of future food insecurity and is not evidence that any screening category improves outcomes.")
    add("- Pairs are dependent (same countries across origins and horizons); there are only a few origin years.")
    add("- Countries that stopped being observed may differ systematically from those that continued; see the diagnostic table.")
    add("- 'Higher quarter' is a relative position among observed estimates, not a policy threshold.")
    add("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", default=str(ROOT / "data" / "processed" / "food_insecurity_percentages.csv"))
    parser.add_argument("--output-dir", default=str(ROOT / "evaluation" / "results"))
    parser.add_argument("--bootstraps", type=int, default=ev.DEFAULT_BOOTSTRAPS)
    parser.add_argument("--seed", type=int, default=ev.DEFAULT_SEED)
    args = parser.parse_args(argv)

    data_path = Path(args.data)
    if not data_path.exists():
        raise SystemExit(f"Data file not found: {data_path}")
    sha = hashlib.sha256(data_path.read_bytes()).hexdigest()

    loaded = fsdata.load_observations(data_path)
    if len(loaded.rejected):
        raise SystemExit(f"{len(loaded.rejected)} rows were rejected at load; fix the data first.")
    observations = loaded.data

    results = ev.run_evaluation(observations, n_boot=args.bootstraps, seed=args.seed)

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name in ("by_horizon", "by_origin", "primary_bootstrap", "attrition"):
        results[name].to_csv(out / f"stale_standing_{name}.csv", index=False)
    results["pairs"].to_csv(out / "stale_standing_pairs.csv", index=False)

    report = build_report(data_path, sha, observations, results, args.bootstraps, args.seed)
    (out / "stale_standing_evaluation.md").write_text(report, encoding="utf-8")
    print(report)
    print(f"\nFiles written to {out}")


if __name__ == "__main__":
    main()
